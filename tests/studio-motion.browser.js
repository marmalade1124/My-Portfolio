async page => {
 const check=(condition,message)=>{if(!condition)throw new Error(message)};
 await page.emulateMedia({reducedMotion:'no-preference'});
 await page.setViewportSize({width:1440,height:900});
 await page.goto('http://127.0.0.1:5180/');
 await page.locator('.studio-gallery[data-ready]').waitFor();
 await page.getByRole('region',{name:'Selected project gallery'}).hover();
 await page.mouse.wheel(0,120);
 const samples=await page.locator('.studio-project').first().evaluate(el=>new Promise(resolve=>{const frames=[];const step=()=>{frames.push(el.style.transform);if(frames.length<25)requestAnimationFrame(step);else resolve(frames)};requestAnimationFrame(step)}));
 check(new Set(samples).size>15,'Scroll must move continuously rather than jump a card');
 check(samples.some(sample=>!/skewX\(0deg\)/.test(sample)),'Velocity deformation missing');
 await page.mouse.move(720,410); await page.mouse.down();
 await page.mouse.move(640,450,{steps:8});
 const tilt=await page.locator('.studio-ring').evaluate(el=>el.style.transform);
 check(!tilt.includes('rotateX(0deg)'),'Direct vertical drag must tilt ring before release');
 await page.mouse.up();
 check(await page.getByRole('dialog').count()===0,'Drag opened a project');
 check(new URL(page.url()).pathname==='/','Drag navigated to a project');
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.waitForFunction(()=>document.querySelector('.studio-ring').style.transform.includes('rotateX(0deg)'));
 const stable=await page.locator('.studio-project').first().evaluate(el=>new Promise(resolve=>{const frames=[];const step=()=>{frames.push(el.style.transform);if(frames.length<10)requestAnimationFrame(step);else resolve(frames)};requestAnimationFrame(step)}));
 check(new Set(stable).size===1,'Reduced motion must stop inertia');
 await page.getByRole('button',{name:'Menu',exact:false}).click();
 await page.keyboard.press('Shift+Tab');
 check(await page.getByRole('dialog',{name:'Navigation',exact:true}).evaluate(el=>el.contains(document.activeElement)),'Focus escaped menu');
 await page.keyboard.press('Escape');
 await page.waitForFunction(()=>document.activeElement?.classList.contains('studio-menu'));
 await page.emulateMedia({reducedMotion:'no-preference'});
 await page.goto('http://127.0.0.1:5180/work/twentyfour');
 const entry=await page.locator('.project-track').evaluate(el=>el.getAnimations().map(animation=>animation.effect.getTiming().duration));
 check(entry.includes(1700),'Project entry should match horizontal 1.7 second transition');
 await page.getByRole('button',{name:'Menu',exact:true}).click();
 await page.keyboard.press('Escape');
 check(new URL(page.url()).pathname==='/work/twentyfour','Closing menu should not close project');
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.locator('.project-scroll').evaluate(el=>{el.scrollTop=el.scrollHeight});
 await page.locator('.project-scroll').hover();
 await page.mouse.wheel(0,2500);
 await page.waitForURL('**/work/picolor');
 await page.keyboard.press('Escape');
 await page.waitForURL('http://127.0.0.1:5180/');
 await page.getByRole('button',{name:'Showcase',exact:true}).waitFor();
 await page.screenshot({path:'output/playwright/ring-final-desktop.png'});
}
