import assert from 'node:assert/strict';
import { advanceRing, cardPose, offsetFrom, wrap } from '../src/components/studio/ringPhysics.ts';
const state=()=>({position:0,velocity:0,target:null,tilt:0,speed:0});
assert.equal(wrap(-1,7),6);
assert.equal(offsetFrom(6,0,7),-1);
const moving=state(); moving.velocity=.08; moving.tilt=12;
advanceRing(moving,1,false);
assert(moving.position>0 && moving.velocity>0 && moving.velocity<.08,'Wheel impulse should move and decay');
assert(moving.speed>0,'Motion should deform the card');
assert(cardPose(3,moving,7,720).includes('scaleX(-1)'),'Rear cards should face the viewer');
for(let i=0;i<1200;i++)advanceRing(moving,1,false);
assert(Math.abs(moving.position-Math.round(moving.position))<.001,'Momentum should settle on a card');
assert.equal(moving.velocity,0); assert.equal(moving.tilt,0);
const targeted=state(); targeted.target=4;
for(let i=0;i<120;i++)advanceRing(targeted,1,false);
assert.equal(targeted.position,4); assert.equal(targeted.target,null);
const dragging=state(); dragging.position=1.25; dragging.velocity=.1; dragging.tilt=8;
advanceRing(dragging,1,true);
assert.equal(dragging.position,1.25,'Drag position must remain under direct control');
assert.equal(dragging.tilt,8);
for(const count of [6,7,29])for(const position of [-10000,-.1,0,9999])assert(Number.isFinite(offsetFrom(0,position,count)));
console.log('Ring physics: inertia, settling, targeting, drag, wrapping and rear-card orientation passed.');
